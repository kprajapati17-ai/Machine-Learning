# ==========================================
# 6. Prediction Function
# ==========================================

def predict_loan_default(person):

    prediction = model.predict(person)
    probability = model.predict_proba(person)

    result = "Loan Default" if prediction[0] == 1 else "No Loan Default"

    print(f"\nDebt-to-Income Ratio: {person[0, 0]}%")
    print(f"Credit Score: {person[0, 1]}")
    print(f"Prediction: {result}")

    print(
        f"Probability of No Loan Default: "
        f"{probability[0, 0]:.2%}"
    )

    print(
        f"Probability of Loan Default: "
        f"{probability[0, 1]:.2%}"
    )


